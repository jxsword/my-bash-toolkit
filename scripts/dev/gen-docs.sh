#!/usr/bin/env bash
# script-name: gen-docs
# description: 扫描 scripts/ 全部 .sh，从头部 tag 与函数级标注批量抽取生成 docs/SCRIPTS.md
# usage: gen-docs.sh [输出文件]
# option: （位置参数）    输出文件路径，默认 docs/SCRIPTS.md
# example: make docs
# env: ubuntu-26.04, wsl-ubuntu-26.04, git-bash
# deps: bash, awk, coreutils
# category: dev

set -u -o pipefail

_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
_OUTPUT="${1:-$_ROOT/docs/SCRIPTS.md}"
readonly -a _DOMAINS=(
  system security dev text files net ops install wsl lib
)

# env: ubuntu-26.04, wsl-ubuntu-26.04, git-bash
# fn: 提取头部注释块（shebang 若有之后、首个空行之前）
header_block() {
  local file="$1" start=1
  if head -n 1 "$file" | grep -q '^#!'; then
    start=2
  fi
  awk -v s="$start" 'NR<s {next} /^[[:space:]]*$/ {exit} {print}' "$file"
}

# env: ubuntu-26.04, wsl-ubuntu-26.04, git-bash
# fn: 读取头部指定 tag 的值（首个命中）
get_tag_value() {
  local file="$1" key="$2" line val
  while IFS= read -r line; do
    line="${line#\# }"
    if [[ "${line%%:*}" == "$key" ]]; then
      val="${line#*:}"
      printf '%s\n' "${val# }"
      return 0
    fi
  done < <(header_block "$file")
  return 1
}

# env: ubuntu-26.04, wsl-ubuntu-26.04, git-bash
# fn: 输出函数清单 TSV（FN\t名称\tenv\t说明）
func_table() {
  local file="$1" fnre
  fnre="^[[:space:]]*(function[[:space:]]+)?"
  fnre="${fnre}[A-Za-z_][A-Za-z0-9_]*[[:space:]]*[(][)]"
  awk -v fnre="$fnre" '
    BEGIN { env = ""; fn = "" }
    /^[[:space:]]*$/ { env = ""; fn = ""; next }
    /^[[:space:]]*#/ {
      line = $0
      sub(/^[[:space:]]*#[[:space:]]*/, "", line)
      if (line ~ /^env:/) { env = substr(line, 6) }
      if (line ~ /^fn:/) { fn = substr(line, 5) }
      next
    }
    $0 ~ fnre {
      name = $0
      sub(/[(][)].*/, "", name)
      sub(/^[[:space:]]*function[[:space:]]+/, "", name)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", name)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", env)
      printf "FN\t%s\t%s\t%s\n", name, env, fn
      env = ""; fn = ""
      next
    }
  ' "$file"
}

# env: ubuntu-26.04, wsl-ubuntu-26.04, git-bash
# fn: 解析头部 tag 并输出单个脚本的 markdown 段落
emit_script_doc() {
  local file="$1" rel line key val o
  rel="${file#"$_ROOT/"}"
  local name="" desc="" usage="" cenv="" deps=""
  local -a opts=() examples=()
  while IFS= read -r line; do
    line="${line#\# }"
    key="${line%%:*}"
    val="${line#*:}"
    val="${val# }"
    case "$key" in
      script-name) name="$val" ;;
      description) desc="$val" ;;
      usage) usage="$val" ;;
      env) cenv="$val" ;;
      deps) deps="$val" ;;
      option) opts+=("$val") ;;
      example) examples+=("$val") ;;
    esac
  done < <(header_block "$file")
  echo "### ${name}（${rel}）"
  echo
  echo "- 说明: ${desc}"
  echo "- 用法: \`${usage}\`"
  echo "- 支持 env: \`${cenv}\`"
  if [[ -n "$deps" ]]; then
    echo "- 依赖: ${deps}"
  fi
  if ((${#opts[@]} > 0)); then
    echo "- 选项:"
    for o in "${opts[@]}"; do
      echo "  - \`${o}\`"
    done
  fi
  if ((${#examples[@]} > 0)); then
    echo "- 示例:"
    for o in "${examples[@]}"; do
      echo "  - \`${o}\`"
    done
  fi
  emit_func_table "$file"
  echo
}

# env: ubuntu-26.04, wsl-ubuntu-26.04, git-bash
# fn: 输出脚本的函数 markdown 表（含 env 与说明）
emit_func_table() {
  local file="$1" fn_out kind fname fenv fdesc
  fn_out="$(func_table "$file")"
  if [[ -z "$fn_out" ]]; then
    return 0
  fi
  echo "- 函数:"
  echo
  echo "  | 函数 | env | 说明 |"
  echo "  |---|---|---|"
  while IFS=$'\t' read -r kind fname fenv fdesc; do
    [[ "$kind" == "FN" ]] || continue
    echo "  | \`${fname}\` | ${fenv:-（同脚本）} | ${fdesc:-} |"
  done <<< "$fn_out"
}

# env: ubuntu-26.04, wsl-ubuntu-26.04, git-bash
# fn: 遍历分类输出整份文档并原子落盘
main() {
  local -a files=()
  mapfile -t files < <(find "$_ROOT/scripts" -name '*.sh' | sort)
  if ((${#files[@]} == 0)); then
    echo "gen-docs: scripts/ 下没有 .sh 文件" >&2
    return 1
  fi
  local -A by_cat=()
  local f cat d k known
  for f in "${files[@]}"; do
    cat="$(get_tag_value "$f" category || true)"
    by_cat["${cat:-uncategorized}"]+="${f}"$'\n'
  done
  local tmp
  tmp="$(mktemp)"
  {
    echo "<!-- AUTO-GENERATED by scripts/dev/gen-docs.sh — DO NOT EDIT -->"
    echo "<!-- 生成时间: $(date '+%F %T %Z') -->"
    echo
    echo "# 脚本功能说明（自动生成）"
    echo
    echo "由 \`scripts/dev/gen-docs.sh\` 从脚本注释批量抽取，禁止手改；"
    echo "修改脚本注释后运行 \`make docs\` 重新生成并随代码提交。"
    echo
    for d in "${_DOMAINS[@]}"; do
      [[ -n "${by_cat[$d]:-}" ]] || continue
      echo "## ${d}"
      echo
      while IFS= read -r f; do
        [[ -n "$f" ]] || continue
        emit_script_doc "$f"
      done <<< "${by_cat[$d]}"
    done
    for k in "${!by_cat[@]}"; do
      known="false"
      for d in "${_DOMAINS[@]}"; do
        [[ "$k" == "$d" ]] && known="true"
      done
      if [[ "$known" == "true" ]]; then
        continue
      fi
      echo "## ${k}（未归类，请补 category tag）"
      echo
      while IFS= read -r f; do
        [[ -n "$f" ]] || continue
        emit_script_doc "$f"
      done <<< "${by_cat[$k]}"
    done
  } > "$tmp"
  printf "%s\n" "$(cat "$tmp")" > "$tmp"
  mv "$tmp" "$_OUTPUT"
  echo "gen-docs: 已生成 $_OUTPUT"
}

main "$@"
